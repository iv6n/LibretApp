/// Drives the "Cuidados" tab: registering a pending task must create a
/// CareRecord and push the task out of the pending list once the parent
/// reloads — the same loop the Agenda relies on to stop reminding.
///
/// Uses an in-memory [CareRepository] rather than the real Isar-backed one:
/// testWidgets runs inside a fake-async clock that real Isar I/O (native FFI
/// callbacks on their own OS thread) never resolves within, so this stays a
/// plain-Dart fake — the same reason `registro_reproduccion_flow_test.dart`
/// fakes its repositories instead of hitting Isar directly.
library;

