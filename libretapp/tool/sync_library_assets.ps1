<#
Syncs the compiled Libretapp book-of-books content from the editorial
`book` repo's dist/ output into this Flutter project's assets, so the
app can bundle every subject book offline.

Source of truth: <BookRepoRoot>/dist/library.json (generated by
tools/generate_library_manifest.ps1 in the book repo) and each book's
dist/<book_id>/content/book-content.json + assets/figures/*.svg.

The app never needs book.json or Markdown sources: book-content.json
already carries title/subtitle/description/stats/adaptive/glossary/
operational/figures for every book, per APP_CONTENT_CONTRACT.md.
#>
param(
    [string]$BookRepoRoot = "C:\Users\Master\Desktop\New folder (2)\book",
    [string]$Root = ".."
)

$ErrorActionPreference = "Stop"
$flutterRoot = (Resolve-Path $Root).Path
$bookRoot = (Resolve-Path $BookRepoRoot).Path
$distRoot = Join-Path $bookRoot "dist"
$libraryManifestPath = Join-Path $distRoot "library.json"

if (-not (Test-Path -LiteralPath $libraryManifestPath -PathType Leaf)) {
    throw "library.json not found at $libraryManifestPath. Run tools\generate_library_manifest.ps1 in the book repo first."
}

$library = Get-Content -Raw -LiteralPath $libraryManifestPath -Encoding UTF8 | ConvertFrom-Json

$assetsRoot = Join-Path $flutterRoot "assets\library"
if (Test-Path -LiteralPath $assetsRoot -PathType Container) {
    Remove-Item -LiteralPath $assetsRoot -Recurse -Force
}
New-Item -ItemType Directory -Path $assetsRoot -Force | Out-Null

Copy-Item -LiteralPath $libraryManifestPath -Destination (Join-Path $assetsRoot "library.json") -Force

$regionConfigPath = Join-Path $bookRoot "regions\mexico-regions.json"
if (Test-Path -LiteralPath $regionConfigPath -PathType Leaf) {
    Copy-Item -LiteralPath $regionConfigPath -Destination (Join-Path $assetsRoot "mexico-regions.json") -Force
}

foreach ($book in $library.books) {
    $bookId = $book.book_id
    $sourcePackageDir = Join-Path $distRoot $book.package_dir
    $targetBookDir = Join-Path $assetsRoot $bookId

    $sourceContent = Join-Path $sourcePackageDir ($book.content_path -replace '/', '\')
    if (-not (Test-Path -LiteralPath $sourceContent -PathType Leaf)) {
        throw "${bookId}: missing compiled content at $sourceContent"
    }
    $targetContentDir = Join-Path $targetBookDir "content"
    New-Item -ItemType Directory -Path $targetContentDir -Force | Out-Null
    Copy-Item -LiteralPath $sourceContent -Destination (Join-Path $targetContentDir "book-content.json") -Force

    $sourceFiguresDir = Join-Path $sourcePackageDir "assets\figures"
    if (Test-Path -LiteralPath $sourceFiguresDir -PathType Container) {
        $targetFiguresDir = Join-Path $targetBookDir "assets\figures"
        New-Item -ItemType Directory -Path $targetFiguresDir -Force | Out-Null
        foreach ($svg in Get-ChildItem -LiteralPath $sourceFiguresDir -File -Filter "*.svg") {
            Copy-Item -LiteralPath $svg.FullName -Destination (Join-Path $targetFiguresDir $svg.Name) -Force
        }
    }

    Write-Host "Synced $bookId -> $targetBookDir"
}

Write-Host ""
Write-Host "Done. Books synced: $($library.books.Count)."
Write-Host "Make sure pubspec.yaml declares, for each book_id:"
Write-Host "  assets/library/<book_id>/content/"
Write-Host "  assets/library/<book_id>/assets/figures/"
Write-Host "plus assets/library/library.json"
